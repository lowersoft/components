// Even-odd ray casting.
const inside = (lon, lat, outline) => {
  let hit = false;
  for (let i = 0, j = outline.length - 1; i < outline.length; j = i++) {
    const [xi, yi] = outline[i];
    const [xj, yj] = outline[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
};

const isLand = (lon, lat) => OUTLINES.some((outline) => inside(lon, lat, outline));

/**
 * Dots on land in rows of latitude, `step` degrees apart along both ways, so
 * the rows bunch into arcs towards the limb like a printed globe. Flat
 * [latitude, longitude] radians.
 */
export const landDots = (step) => {
  const dots = [];
  for (let lat = -58; lat <= 82; lat += step) {
    const across = step / Math.max(0.1, Math.cos((lat * Math.PI) / 180));
    for (let lon = -180; lon < 180; lon += across) {
      if (isLand(lon, lat)) dots.push((lat * Math.PI) / 180, (lon * Math.PI) / 180);
    }
  }
  return new Float32Array(dots);
};
