const WIDTH = 5;
const GAP = 1;
const SPACE = 3;

/**
 * Lays `text` out in the font: the filled cells as `[x, y]` pairs, and the
 * grid's size in cells. Letters the font lacks are left out; a space is
 * three cells wide. The grid is seven rows tall, eight when a letter has a
 * tail.
 */
export const layout = (text) => {
  const cells = [];
  let x = 0;
  let rows = 7;
  for (const char of String(text)) {
    if (char === ' ') {
      x += SPACE;
      continue;
    }
    const glyph = GLYPHS[char];
    if (!glyph) continue;
    const lines = glyph.split(' ');
    rows = Math.max(rows, lines.length);
    lines.forEach((line, y) => [...line].forEach((cell, dx) => cell === '#' && cells.push([x + dx, y])));
    x += WIDTH + GAP;
  }
  return { cells, columns: Math.max(1, x - GAP), rows };
};
